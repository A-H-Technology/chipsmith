#!/usr/bin/env python3
"""Generate examples/zybo-shapes/src/top.v: every block RAM and multiplier
shape of crates/chipsmith-xc7/tests/designs in one design, each fed from its
own xorshift128 stream and folded into its own 32-bit MISR, all read back in
USER1. sim.cpp runs the same top in Verilator for the signatures the board
must give.

    examples/zybo-shapes/gen.py > examples/zybo-shapes/src/top.v
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
DESIGNS = ROOT / "crates/chipsmith-xc7/tests/designs"
SHAPES = sorted((DESIGNS / "bram").glob("*.v")) + sorted((DESIGNS / "dsp").glob("*.v"))
CYCLES = 1 << 20  # ~8.4 ms at 125 MHz, then every signature holds
TAG = 0x53484150  # "SHAP"
CLOCKS = {"clk", "clk2"}
PORT = re.compile(r"(input|output)\s+(?:reg\s+)?(?:signed\s+)?(?:\[(\d+):0\]\s+)?(\w+)")


def ports(path):
    text = re.sub(r"//.*", "", path.read_text())
    m = re.search(r"module\s+(\w+)\s*\((.*?)\);", text, re.S)
    return m.group(1), [(d, int(w or 0) + 1, n) for d, w, n in PORT.findall(m.group(2))]


def shape(i, path):
    name, ps = ports(path)
    ins = [(w, n) for d, w, n in ps if d == "input" and n not in CLOCKS]
    outs = [(w, n) for d, w, n in ps if d == "output"]
    width = sum(w for w, _ in ins)
    assert width <= 128, (name, width)
    owidth = sum(w for w, _ in outs)
    lines = [f"  // {name}: {width} input bits, {owidth} output bits"]
    lines.append(f"  reg [63:0] {name}_s0 = 64'h{(0x9E3779B97F4A7C15 * (2 * i + 1)) & (2**64 - 1):016x};")
    lines.append(f"  reg [63:0] {name}_s1 = 64'h{(0xD1B54A32D192ED03 * (2 * i + 3)) & (2**64 - 1):016x};")
    lines.append(f"  wire [63:0] {name}_t = {name}_s0 ^ ({name}_s0 << 23);")
    lines.append(f"  always @(posedge clk) if (run) begin")
    lines.append(f"    {name}_s0 <= {name}_s1;")
    lines.append(f"    {name}_s1 <= {name}_t ^ {name}_s1 ^ ({name}_t >> 17) ^ ({name}_s1 >> 26);")
    lines.append("  end")
    lines.append(f"  wire [127:0] {name}__rnd = {{{name}_s1, {name}_s0}};")
    conns = []
    at = 0
    for w, n in ins:
        if n == "rst" and w == 1:
            # A reset half the time would hide everything behind it.
            src = f"&{name}__rnd[{at + 2}:{at}]"
            at += 3
        else:
            src = f"{name}__rnd[{at + w - 1}:{at}]"
            at += w
        conns.append(f".{n}({src})")
    for w, n in outs:
        lines.append(f"  wire [{w - 1}:0] {name}__out_{n};")
        conns.append(f".{n}({name}__out_{n})")
    clocks = [n for d, w, n in ps if n in CLOCKS]
    # Both of dualclock's clocks are the board's: its ports are clocked
    # from two pins of the block, at one frequency.
    conns = [f".{c}(clk)" for c in clocks] + conns
    lines.append(f"  {name} u_{name} ({', '.join(conns)});")
    folded = f"{{{', '.join(f'{name}__out_{n}' for _, n in reversed(outs))}}}"
    chunks = (owidth + 31) // 32
    pad = chunks * 32 - owidth
    padded = f"{{{pad}'d0, {folded}}}" if pad else folded
    lines.append(f"  wire [{chunks * 32 - 1}:0] {name}__fold = {padded};")
    fold = " ^ ".join(f"{name}__fold[{32 * k + 31}:{32 * k}]" for k in range(chunks))
    lines.append(f"  reg [31:0] {name}_m = 32'd0;")
    lines.append(
        f"  always @(posedge clk) if (run) "
        f"{name}_m <= {{{name}_m[30:0], 1'b0}} ^ ({name}_m[31] ? 32'h04C11DB7 : 32'd0) ^ {fold};"
    )
    return name, "\n".join(lines)


def main():
    built = [shape(i, p) for i, p in enumerate(SHAPES)]
    names = [n for n, _ in built]
    dr = 64 + 32 * len(names)
    print(f"""// Generated by gen.py: don't edit. Every shape of
// crates/chipsmith-xc7/tests/designs (block RAM and multipliers) on the
// Zybo, its inputs from its own xorshift128 stream, its outputs folded into
// a 32-bit MISR, all stopping after {CYCLES} cycles. USER1 ({dr} bits, LSB
// first): "SHAP", the cycles run, then each shape's signature in this order:
//   {", ".join(names)}
// sim.cpp gives the signatures the RTL defines.
module top(input clk, output [3:0] led);
  // The end of configuration (GSR) reaches the registers over a cycle or so
  // of the 125 MHz clock, so streams and signatures started straight from it
  // began a cycle apart now and then (the same wrong signature twice in 8
  // loads). One flop starts them all, 256 cycles in; until then the shapes
  // see their streams' first values and rewrite the same words.
  reg [7:0] settle = 8'd0;
  reg go = 1'b0;
  always @(posedge clk) begin
    if (~&settle) settle <= settle + 1'b1;
    go <= &settle;
  end
  reg [31:0] cycles = 32'd0;
  wire run = go && cycles != 32'd{CYCLES};
  always @(posedge clk) if (run) cycles <= cycles + 1'b1;
""")
    for _, text in built:
        print(text)
    sigs = ", ".join(f"{n}_m" for n in reversed(names))
    print(f"""
  wire [{dr - 1}:0] result = {{{sigs}, cycles, 32'h{TAG:08x}}};
  assign led = {{3'd0, go && !run}};  // LD0: done
`ifndef VERILATOR
  wire tck, sel, capture, shift, tdi;
  reg [{dr - 1}:0] dr = 0;
  BSCANE2 #(.JTAG_CHAIN(1)) bscan (
    .TCK(tck), .SEL(sel), .CAPTURE(capture), .SHIFT(shift), .TDI(tdi),
    .TDO(dr[0])
  );
  always @(posedge tck)
    if (sel)
      if (capture) dr <= result;
      else if (shift) dr <= {{tdi, dr[{dr - 1}:1]}};
`endif
endmodule""")


if __name__ == "__main__":
    main()
